#!/usr/bin/env node
/**
 * Vendors the shared mod kit into each mod (docs/adr/0001-vendored-mod-kit.md).
 *
 *   node tools/sync-kit.mjs [mod...]            writes mods/<mod>/src/_kit/ from libs/mod-kit/src/
 *   node tools/sync-kit.mjs [mod...] --check    reports drift, writes nothing, exits 1 on drift
 *   --root <dir>                                run against another workspace (used by the tests)
 *
 * A mod's `kit` field in package.json lists kit module names (paths under libs/mod-kit/src without
 * the extension). Each listed module, and every kit module it imports, is copied under a
 * generated-file header. Files in _kit/ that are no longer reachable are removed.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const args = process.argv.slice(2)
const rootFlag = args.indexOf('--root')
const root =
  rootFlag >= 0
    ? path.resolve(args[rootFlag + 1])
    : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = args.includes('--check')
const named = args.filter((a, i) => !a.startsWith('--') && (rootFlag < 0 || i !== rootFlag + 1))

const modsDir = path.join(root, 'mods')
const kitDir = path.join(root, 'libs', 'mod-kit', 'src')
const EXT = '.ts'

const header = name =>
  `// Generated by tools/sync-kit.mjs from libs/mod-kit/src/${name}${EXT}. Do not edit; edit the kit and run sync-kit.\n`

const fail = message => {
  console.error(message)
  process.exit(1)
}

const allMods = () =>
  existsSync(modsDir)
    ? readdirSync(modsDir, { withFileTypes: true })
        .filter(d => d.isDirectory() && existsSync(path.join(modsDir, d.name, 'package.json')))
        .map(d => d.name)
    : []

const kitFile = name => path.join(kitDir, name + EXT)

const importsOf = (name, text) => {
  const found = []
  const re = /(?:from\s*|import\s*\(?\s*|import\s+)['"](\.{1,2}\/[^'"]+)['"]/g
  for (let m; (m = re.exec(text));) {
    const rel = m[1].replace(/\.ts$/, '')
    found.push(path.posix.normalize(path.posix.join(path.posix.dirname(name), rel)))
  }
  return found
}

/** The listed modules plus every kit module they import, as name -> source text. */
const closure = (mod, list) => {
  const out = new Map()
  const queue = [...list]
  while (queue.length) {
    const name = queue.shift()
    if (out.has(name)) continue
    if (name.startsWith('..') || !existsSync(kitFile(name)))
      fail(`${mod}: kit module "${name}" does not exist in libs/mod-kit/src`)
    const text = readFileSync(kitFile(name), 'utf8')
    out.set(name, text)
    queue.push(...importsOf(name, text))
  }
  return out
}

const filesUnder = dir =>
  existsSync(dir)
    ? readdirSync(dir, { recursive: true, withFileTypes: true })
        .filter(d => d.isFile())
        .map(d => path.relative(dir, path.join(d.parentPath, d.name)).split(path.sep).join('/'))
    : []

const prune = dir => {
  for (const d of readdirSync(dir, { withFileTypes: true }).filter(d => d.isDirectory())) {
    prune(path.join(dir, d.name))
  }
  if (!readdirSync(dir).length) rmSync(dir, { recursive: true })
}

const known = new Set(allMods())
for (const n of named) if (!known.has(n)) fail(`unknown mod "${n}"`)
const mods = named.length ? named : [...known]

// Resolve every mod first so an unknown module name writes nothing at all.
const plans = mods.map(mod => {
  const { kit = [] } = JSON.parse(readFileSync(path.join(modsDir, mod, 'package.json'), 'utf8'))
  const want = new Map()
  for (const [name, text] of closure(mod, kit)) want.set(name + EXT, header(name) + text)
  return { mod, want, dir: path.join(modsDir, mod, 'src', '_kit') }
})

let drift = 0
for (const { mod, want, dir } of plans) {
  const have = filesUnder(dir)
  const report = (file, why) => {
    console.error(`${mod}: src/_kit/${file} ${why}`)
    drift++
  }
  for (const [file, text] of want) {
    const target = path.join(dir, file)
    const current = existsSync(target) ? readFileSync(target, 'utf8') : undefined
    if (current === text) continue
    if (check) {
      report(file, current === undefined ? 'is missing' : 'differs from the kit')
      continue
    }
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, text)
    console.log(`${mod}: wrote src/_kit/${file}`)
  }
  for (const file of have) {
    if (want.has(file)) continue
    if (check) {
      report(file, 'is not in the kit list')
      continue
    }
    rmSync(path.join(dir, file))
    console.log(`${mod}: removed src/_kit/${file}`)
  }
  if (!check && existsSync(dir)) prune(dir)
}

if (drift) console.error('Run `node tools/sync-kit.mjs` to update the vendored copies.')
process.exit(drift ? 1 : 0)
