#!/usr/bin/env node
/**
 * Keeps Craftory's copy of mattpocock-skills' setup templates byte-identical to upstream.
 *
 *   node tools/vendor-craftory-templates.mjs --from <mattpocock-skills version folder>
 *       copies the upstream files into mods/craftory/tests/fixtures/mattpocock-skills-<v>/
 *       and regenerates the two TypeScript views of them.
 *   node tools/vendor-craftory-templates.mjs --check
 *       fails when either view differs from the raw fixture files.
 *
 * `claude plugin test` can import only code files, so the raw .md fixtures are mirrored into
 * tests/upstream-fixtures.ts, and the five templates Craftory writes are mirrored into the
 * generated region of src/templates.ts. The tests compare those two views.
 *
 * The wayfinder fixtures under tests/fixtures/wayfinder/<skills range>/<source>/<scenario>/ are
 * repo-owned, not copied from upstream. Each starts with a header comment saying whether it was
 * "captured" or "hand-made". They are compiled into tests/wayfinder-fixtures.ts the same way.
 */
import { copyFileSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'mods', 'craftory')
const VERSION = '1.3.1'
const fixtures = join(root, 'tests', 'fixtures', `mattpocock-skills-${VERSION}`)
const SKILL = 'skills/engineering/setup-matt-pocock-skills'
const SOURCES = {
  'GLOSSARY.md': 'GLOSSARY.md',
  'SKILL.md': `${SKILL}/SKILL.md`,
  'issue-tracker-github.md': `${SKILL}/issue-tracker-github.md`,
  'issue-tracker-gitlab.md': `${SKILL}/issue-tracker-gitlab.md`,
  'issue-tracker-local.md': `${SKILL}/issue-tracker-local.md`,
  'triage-labels.md': `${SKILL}/triage-labels.md`,
  'domain.md': `${SKILL}/domain.md`,
}
const TEMPLATE_NAMES = [
  'issue-tracker-github',
  'issue-tracker-gitlab',
  'issue-tracker-local',
  'triage-labels',
  'domain',
]

const args = process.argv.slice(2)
const from = args[0] === '--from' ? args[1] : undefined
if (from) {
  mkdirSync(fixtures, { recursive: true })
  for (const [name, path] of Object.entries(SOURCES))
    copyFileSync(join(from, path), join(fixtures, name))
}

const raw = Object.fromEntries(
  Object.keys(SOURCES).map(name => [name, readFileSync(join(fixtures, name), 'utf8')]),
)

const fixturesTs = `// Generated by tools/vendor-craftory-templates.mjs from tests/fixtures/mattpocock-skills-${VERSION}/*.md. Do not edit.
export const UPSTREAM_FIXTURES: Readonly<Record<string, string>> = ${JSON.stringify(raw, null, 2)}
`

const region = TEMPLATE_NAMES.map(
  name => `  // prettier-ignore\n  '${name}': ${JSON.stringify(raw[`${name}.md`])},`,
).join('\n')
const templatesPath = join(root, 'src', 'templates.ts')
const START = '  // <generated: tools/vendor-craftory-templates.mjs>\n'
const END = '  // </generated>\n'
const current = readFileSync(templatesPath, 'utf8')
const [head, rest] = current.split(START)
const tail = rest.split(END)[1]
const templatesTs = `${head}${START}${region}\n${END}${tail}`

const wayfinderRoot = join(root, 'tests', 'fixtures', 'wayfinder')
const filesUnder = dir =>
  readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name, 'en'))
    .flatMap(entry =>
      entry.isDirectory() ? filesUnder(join(dir, entry.name)) : [join(dir, entry.name)],
    )
const wayfinder = Object.fromEntries(
  filesUnder(wayfinderRoot).map(path => [
    path.slice(wayfinderRoot.length + 1),
    readFileSync(path, 'utf8'),
  ]),
)
for (const [path, text] of Object.entries(wayfinder)) {
  if (!/^<!-- (captured|hand-made):/.test(text)) {
    console.error(`${path}: the first line must be a "captured:" or "hand-made:" comment.`)
    process.exit(1)
  }
}
const wayfinderTs = `// Generated by tools/vendor-craftory-templates.mjs from tests/fixtures/wayfinder/**. Do not edit.
export const WAYFINDER_FIXTURES: Readonly<Record<string, string>> = ${JSON.stringify(wayfinder, null, 2)}
`

const targets = [
  [join(root, 'tests', 'wayfinder-fixtures.ts'), wayfinderTs],
  [join(root, 'tests', 'upstream-fixtures.ts'), fixturesTs],
  [templatesPath, templatesTs],
]
if (args.includes('--check')) {
  const stale = targets.filter(([path, text]) => readFileSync(path, 'utf8') !== text)
  if (stale.length > 0) {
    console.error(`stale: ${stale.map(([path]) => path).join(', ')}. Run the script with --from.`)
    process.exit(1)
  }
} else {
  for (const [path, text] of targets) writeFileSync(path, text)
}
