import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { after, beforeEach, describe, it } from 'node:test'
import { fileURLToPath } from 'node:url'

const tool = path.resolve(path.dirname(fileURLToPath(import.meta.url)), 'sync-kit.mjs')
const dirs = []
after(() => dirs.forEach(d => rmSync(d, { recursive: true, force: true })))

let ws
const put = (rel, text) => {
  mkdirSync(path.dirname(path.join(ws, rel)), { recursive: true })
  writeFileSync(path.join(ws, rel), text)
}
const read = rel => readFileSync(path.join(ws, rel), 'utf8')
const has = rel => existsSync(path.join(ws, rel))
const setKit = (mod, kit) => put(`mods/${mod}/package.json`, JSON.stringify({ name: mod, kit }))
const run = (...a) => {
  const r = spawnSync('node', [tool, '--root', ws, ...a], { encoding: 'utf8' })
  return { code: r.status, out: r.stdout, err: r.stderr }
}
const vendored = mod => `mods/${mod}/src/_kit`

beforeEach(() => {
  ws = mkdtempSync(path.join(tmpdir(), 'sync-kit-'))
  dirs.push(ws)
  put('libs/mod-kit/src/a.ts', "import { b } from './b'\nexport const a = b\n")
  put('libs/mod-kit/src/b.ts', 'export const b = 1\n')
  put('libs/mod-kit/src/c.ts', 'export const c = 2\n')
  setKit('one', ['a'])
  setKit('two', ['c'])
})

describe('sync-kit', () => {
  it('writes the listed modules and their kit imports, with a generated header', () => {
    assert.equal(run().code, 0)
    assert.match(
      read(`${vendored('one')}/a.ts`),
      /^\/\/ Generated by tools\/sync-kit\.mjs.*Do not edit/,
    )
    assert.ok(
      read(`${vendored('one')}/a.ts`).endsWith("import { b } from './b'\nexport const a = b\n"),
    )
    assert.ok(has(`${vendored('one')}/b.ts`))
    assert.ok(!has(`${vendored('one')}/c.ts`))
    assert.ok(has(`${vendored('two')}/c.ts`))
    assert.ok(!has(`${vendored('two')}/a.ts`))
  })

  it('is idempotent', () => {
    run()
    const r = run()
    assert.equal(r.code, 0)
    assert.equal(r.out, '')
    assert.equal(run('--check').code, 0)
  })

  it('removes a vendored file when its name leaves the list', () => {
    run()
    setKit('one', [])
    run()
    assert.ok(!has(`${vendored('one')}/a.ts`))
    assert.ok(!has(`${vendored('one')}/b.ts`))
  })

  it('errors on an unknown kit module and writes nothing', () => {
    setKit('two', ['nope'])
    const r = run()
    assert.notEqual(r.code, 0)
    assert.match(r.err, /two: kit module "nope"/)
    assert.ok(!has(`${vendored('one')}/a.ts`))
  })

  it('syncs only the named mod', () => {
    assert.equal(run('one').code, 0)
    assert.ok(has(`${vendored('one')}/a.ts`))
    assert.ok(!has(`${vendored('two')}/c.ts`))
  })

  it('--check passes when in sync and writes nothing when not', () => {
    assert.notEqual(run('--check').code, 0)
    assert.ok(!has(`${vendored('one')}/a.ts`))
    run()
    assert.equal(run('--check').code, 0)
  })

  it('--check names the mod and file for an edited, deleted or stale copy, or a changed kit', () => {
    run()
    writeFileSync(path.join(ws, vendored('one'), 'a.ts'), 'edited\n')
    let r = run('--check')
    assert.equal(r.code, 1)
    assert.match(r.err, /one: src\/_kit\/a\.ts/)
    assert.match(r.err, /sync-kit/)

    run()
    rmSync(path.join(ws, vendored('one'), 'b.ts'))
    r = run('--check')
    assert.equal(r.code, 1)
    assert.match(r.err, /one: src\/_kit\/b\.ts is missing/)

    run()
    put('libs/mod-kit/src/c.ts', 'export const c = 3\n')
    r = run('--check')
    assert.equal(r.code, 1)
    assert.match(r.err, /two: src\/_kit\/c\.ts/)

    run()
    put(`${vendored('two')}/extra.ts`, 'x\n')
    r = run('--check')
    assert.equal(r.code, 1)
    assert.match(r.err, /two: src\/_kit\/extra\.ts/)
  })
})
